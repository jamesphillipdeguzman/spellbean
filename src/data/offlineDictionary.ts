/**
 * Intelligent procedural generator for words not yet fetched from online API
 */
export function generateFallbackDefinition(word: string): WordDefinition {
  const lower = word.toLowerCase();

  // Check curated list first
  if (CURATED_DICTIONARY[lower]) {
    const cur = CURATED_DICTIONARY[lower];
    return {
      word,
      phonetic: cur.phonetic || `/${word}/`,
      partOfSpeech: cur.partOfSpeech || 'noun',
      definition: cur.definition || `A competition term and designated entry in the official SOT spelling list.`,
      exampleSentence: cur.exampleSentence || `The contestant spelled the word ${word} with great precision.`,
      origin: cur.origin || 'Official SOT Word Bank',
    };
  }

  // Guess part of speech based on common morphological suffixes
  let pos = 'noun';
  if (lower.endsWith('ly')) pos = 'adverb';
  else if (lower.endsWith('ous') || lower.endsWith('ic') || lower.endsWith('able') || lower.endsWith('ive') || lower.endsWith('al') || lower.endsWith('ful')) pos = 'adjective';
  else if (lower.endsWith('ate') || lower.endsWith('ize') || lower.endsWith('ise') || lower.endsWith('ify')) pos = 'verb';

  let example = `The contestant spelled the word ${word} with great precision during the convention.`;
  if (pos === 'verb') {
    example = `The speaker paused to carefully ${word} the difficult matter before the assembly.`;
  } else if (pos === 'adjective') {
    example = `The researcher observed an unusually ${word} specimen during the field study.`;
  } else if (pos === 'adverb') {
    example = `The student listened ${word} to every detail announced by the judge.`;
  }

  return {
    word,
    phonetic: `/${word}/`,
    partOfSpeech: pos,
    definition: `Official SOT competition vocabulary word. Ready for practice and contest inquiry.`,
    exampleSentence: example,
    origin: 'Official SOT®P Spelling List (2026 Revision)',
  };
}

